CREATE TABLE payable (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    request_id UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    branch_id UUID NOT NULL,
    supplier_id UUID NOT NULL,
    supplier_name VARCHAR(200) NOT NULL,
    purchase_receipt_id UUID,
    reference VARCHAR(60) NOT NULL,
    document VARCHAR(160) NOT NULL,
    description VARCHAR(500) NOT NULL,
    issued_on DATE NOT NULL,
    due_on DATE NOT NULL CHECK(due_on>=issued_on),
    amount NUMERIC(19,2) NOT NULL CHECK(amount>0),
    paid_amount NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK(paid_amount>=0 AND paid_amount<=amount),
    status VARCHAR(15) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_by UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancellation_note VARCHAR(500),
    UNIQUE(tenant_id,id),
    UNIQUE(tenant_id,request_id),
    UNIQUE(tenant_id,reference),
    CHECK((status='OPEN' AND paid_amount=0) OR (status='PARTIAL' AND paid_amount>0 AND paid_amount<amount) OR (status='PAID' AND paid_amount=amount) OR (status='CANCELLED' AND paid_amount=0)),
    FOREIGN KEY(tenant_id,branch_id) REFERENCES branch(tenant_id,id),
    FOREIGN KEY(tenant_id,supplier_id) REFERENCES supplier(tenant_id,id),
    FOREIGN KEY(tenant_id,purchase_receipt_id) REFERENCES purchase_receipt(tenant_id,id),
    FOREIGN KEY(tenant_id,created_by) REFERENCES app_user(tenant_id,id)
);
CREATE INDEX ix_payable_tenant_branch_due ON payable(tenant_id,branch_id,due_on);
CREATE TABLE payable_payment (
    id UUID NOT NULL,
    tenant_id UUID NOT NULL,
    payable_id UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    amount NUMERIC(19,2) NOT NULL CHECK(amount>0),
    paid_on DATE NOT NULL,
    method VARCHAR(20) NOT NULL CHECK(method IN ('CASH','BANK_TRANSFER','PIX','OTHER')),
    reference VARCHAR(160) NOT NULL,
    note VARCHAR(500) NOT NULL,
    status VARCHAR(15) NOT NULL CHECK(status IN ('POSTED','REVERSED')),
    created_by UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reversal_request_id UUID,
    reversal_note VARCHAR(500),
    reversed_by UUID,
    reversed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(tenant_id,id),
    UNIQUE(tenant_id,reversal_request_id),
    CHECK((status='POSTED' AND reversal_request_id IS NULL AND reversal_note IS NULL AND reversed_by IS NULL AND reversed_at IS NULL) OR (status='REVERSED' AND reversal_request_id IS NOT NULL AND reversal_note IS NOT NULL AND reversed_by IS NOT NULL AND reversed_at IS NOT NULL)),
    FOREIGN KEY(tenant_id,payable_id) REFERENCES payable(tenant_id,id),
    FOREIGN KEY(tenant_id,created_by) REFERENCES app_user(tenant_id,id),
    FOREIGN KEY(tenant_id,reversed_by) REFERENCES app_user(tenant_id,id)
);
CREATE INDEX ix_payment_payable ON payable_payment(tenant_id,payable_id,created_at);
